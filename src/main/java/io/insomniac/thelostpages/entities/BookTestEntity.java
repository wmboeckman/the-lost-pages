	@Override
	protected PathNavigation createNavigation(Level world) {
		return new FlyingPathNavigation(this, world);
	}

	@Override
	protected void registerGoals() {
		super.registerGoals();
		this.goalSelector.addGoal(1, new Goal() {
			{
				this.setFlags(EnumSet.of(Flag.MOVE));
			}

			public boolean canUse() {
				if (BookTestEntity.this.getTarget() != null && !BookTestEntity.this.getMoveControl().hasWanted()) {
					return true;
				} else {
					return false;
				}
			}

			@Override
			public boolean canContinueToUse() {
				return BookTestEntity.this.getMoveControl().hasWanted() && BookTestEntity.this.getTarget() != null && BookTestEntity.this.getTarget().isAlive();
			}

			@Override
			public void start() {
				LivingEntity livingentity = BookTestEntity.this.getTarget();
				Vec3 vec3d = livingentity.getEyePosition(1);
				BookTestEntity.this.moveControl.setWantedPosition(vec3d.x, vec3d.y, vec3d.z, 2);
			}

			@Override
			public void tick() {
				LivingEntity livingentity = BookTestEntity.this.getTarget();
				if (BookTestEntity.this.getBoundingBox().intersects(livingentity.getBoundingBox())) {
					BookTestEntity.this.doHurtTarget(this.getServerLevel(livingentity), livingentity);
				} else {
					double d0 = BookTestEntity.this.distanceToSqr(livingentity);
					if (d0 < 8) {
						Vec3 vec3d = livingentity.getEyePosition(1);
						BookTestEntity.this.moveControl.setWantedPosition(vec3d.x, vec3d.y, vec3d.z, 2);
					}
				}
			}
		});
		this.goalSelector.addGoal(2, new MeleeAttackGoal(this, 1.75, false) {
			@Override
			protected boolean canPerformAttack(LivingEntity entity) {
				return this.isTimeToAttack() && this.mob.distanceToSqr(entity) < 2.25 && this.mob.getSensing().hasLineOfSight(entity);
			}
		});
		this.goalSelector.addGoal(3, new RandomStrollGoal(this, 2.25, 20) {
			@Override
			protected Vec3 getPosition() {
				RandomSource random = BookTestEntity.this.getRandom();
				double dir_x = BookTestEntity.this.getX() + ((random.nextFloat() * 2 - 1) * 16);
				double dir_y = BookTestEntity.this.getY() + ((random.nextFloat() * 2 - 1) * 16);
				double dir_z = BookTestEntity.this.getZ() + ((random.nextFloat() * 2 - 1) * 16);
				return new Vec3(dir_x, dir_y, dir_z);
			}
		});
		this.goalSelector.addGoal(4, new RandomLookAroundGoal(this));
		this.targetSelector.addGoal(5, new NearestAttackableTargetGoal(this, Player.class, true, false));
		this.targetSelector.addGoal(6, new HurtByTargetGoal(this).setAlertOthers());
		this.goalSelector.addGoal(1, new RangedAttackGoal(this, 1.25, 80, 12f) {
			@Override
			public boolean canContinueToUse() {
				return this.canUse();
			}
		});
	}

